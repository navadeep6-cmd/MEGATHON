#!/usr/bin/env python3
"""Step 11 - assemble reports/RESULTS.md from the JSON reports.

Every number in RESULTS.md comes from files produced by the earlier steps;
nothing is typed in by hand.
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from catsuggest.config import Paths, load_config  # noqa: E402
from catsuggest.io_utils import read_json  # noqa: E402


def f3(x):
    return "-" if x is None else "%.3f" % x


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(out)


def load(P, name):
    path = P.report(name)
    return read_json(path) if os.path.exists(path) else None


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--config", default=None)
    args = ap.parse_args()
    cfg = load_config(args.config)
    P = Paths(cfg)
    ks = [int(k) for k in cfg["eval"]["ks"]]
    md = ["# Results", "",
          "Generated by `scripts/s11_report.py` from the JSON files in `reports/`. "
          "Test split = later uploads by uploaders unseen in training, near-duplicates removed.", ""]

    ds = load(P, "data_stats.json")
    if ds:
        md += ["## Data", "",
               table(["item", "value"], [
                   ["images (train / val / test)", "%s / %s / %s" % (ds["splits"].get("train", 0),
                                                                     ds["splits"].get("val", 0),
                                                                     ds["splits"].get("test", 0))],
                   ["categories in vocabulary", "%s (%s image labels + %s parent-category distractors)" % (
                       ds["categories"], ds.get("label_categories", "-"), ds.get("distractor_categories", 0))],
                   ["mean labels per image", "%.2f" % ds["labels_per_image_mean"]],
                   ["category bands", ds["bands"]],
                   ["category types", ds["types"]],
                   ["split mode", ds["split_mode"]],
                   ["near-duplicates removed (dHash)", ds["near_duplicates_removed"]],
                   ["filtered out", ds["filtered"]],
                   ["time range per split", ds["time_range"]],
               ]), ""]

    m = load(P, "metrics.json")
    if m:
        main_sys = m["main_system"]
        md += ["## Accuracy on new images (test split, %d images)" % m["n_test_images"], "",
               "Main system: **%s**. Candidate recall (upper bound on R@k): %s; mean candidates/image: %.0f."
               % (main_sys, f3(m["candidate_recall"]), m["mean_candidates_per_image"]), ""]
        header = ["system"] + ["P@%d" % k for k in ks] + ["R@%d" % k for k in ks] + ["F1@5", "mAP",
                                                                                         "macro mAP", "hP@5"]
        rows = []
        for name, res in m["systems"].items():
            s, mac, h = res["sample"], res["macro"], res["hier_P@k"]
            label = "**%s**" % name if name == main_sys else name
            rows.append([label] + [f3(s.get("P@%d" % k)) for k in ks] + [f3(s.get("R@%d" % k)) for k in ks]
                        + [f3(s.get("F1@5")), f3(s.get("mAP")), f3(mac.get("macro_mAP")), f3(h.get("hP@5"))])
        md += [table(header, rows), "",
               "P/R/F1/mAP are sample-wise (per image); macro mAP is per category; hP@5 gives 0.5 credit "
               "to a predicted ancestor/descendant of a true label.", ""]

        def macro_table(title, key):
            rows = []
            for g, res in m.get(key, {}).items():
                if res.get("n_categories", 0) == 0:
                    continue
                rows.append([g, res["n_categories"], f3(res.get("macro_mAP")), f3(res.get("macro_R@5")),
                             f3(res.get("macro_R@10")), f3(res.get("macro_F1@5"))])
            return ["### " + title, "", table(["group", "categories", "macro mAP", "macro R@5", "macro R@10",
                                               "macro F1@5"], rows), ""]

        def sample_table(title, key):
            rows = []
            for g, res in m.get(key, {}).items():
                if res.get("n_images", 0) == 0:
                    continue
                rows.append([g, res["n_images"], f3(res.get("P@1")), f3(res.get("P@5")), f3(res.get("R@10")),
                             f3(res.get("mAP"))])
            return ["### " + title, "", table(["group", "images", "P@1", "P@5", "R@10", "mAP"], rows), ""]

        md += macro_table("Long tail: by training frequency band", "by_band")
        md += macro_table("Category breadth: by category type", "by_type")
        md += macro_table("Category label script (language audit)", "by_script")
        md += sample_table("Geographic audit: by region of the geotag", "by_region")
        md += sample_table("By original image resolution", "by_resolution")
        md += sample_table("With vs without title/description", "by_metadata_present")

    rv = load(P, "review.json")
    if rv:
        md += ["## Strict vs reviewed score", "",
               "%d sampled 'wrong' suggestions were reviewed by a human; %.1f%% were actually correct "
               "(missing labels on Commons)." % (rv["reviewed"], 100 * rv["fraction_actually_correct"]), "",
               table(["metric", "strict", "reviewed (estimate)"],
                     [[k, f3(v["strict"]), f3(v["reviewed"])] for k, v in rv["adjusted"].items()]), ""]

    rb = load(P, "robustness.json")
    if rb:
        rows = [[name, f3(r.get("P@1")), f3(r.get("P@5")), f3(r.get("R@10")), f3(r.get("mAP"))]
                for name, r in rb["corruptions"].items()]
        md += ["## Robustness to image quality (%d test images)" % rb["n_images"], "",
               table(["corruption", "P@1", "P@5", "R@10", "mAP"], rows), ""]

    bm = load(P, "benchmark.json")
    if bm:
        lat = bm["latency_ms_end_to_end"]
        md += ["## Efficiency", "",
               table(["item", "value"], [
                   ["machine / device", "%s / %s" % (bm["machine"]["platform"], bm["machine"]["device"])],
                   ["encoder", bm["encoder"]],
                   ["end-to-end latency p50 / p95", "%.1f / %.1f ms" % (lat["p50"], lat["p95"])],
                   ["single-stream throughput", "%.1f images/s" % bm["single_stream_images_per_s"]],
                   ["encoder batched throughput", "%.1f images/s" % bm["encoder_batched_images_per_s"]],
                   ["index", "%d vectors x %d-d, %s (%s), %.1f MB" % (
                       bm["index"]["vectors"], bm["index"]["dim"], bm["index"]["kind"], bm["index"]["backend"],
                       bm["index"]["bytes"] / 1e6)],
                   ["peak process memory", "-" if bm["peak_rss_mb"] is None else "%.0f MB" % bm["peak_rss_mb"]],
                   ["10^8 images: flat fp16 vs PQ 64 B", "%.0f GB vs %.1f GB" % (
                       bm["projection_1e8_images"]["flat_fp16_GB"], bm["projection_1e8_images"]["pq_64B_GB"])],
                   ["10^5 uploads/day on this machine, single stream", "%.2f hours" % (
                       bm["projection_1e8_images"]["daily_uploads_1e5_at_measured_single_stream_hours"])],
               ]), ""]

    fu = load(P, "fusion.json")
    if fu and fu["models"].get("logreg", {}).get("standardised_coefficients"):
        coefs = fu["models"]["logreg"]["standardised_coefficients"]
        md += ["## Fusion weights (logistic regression, standardised features)", "",
               table(["feature", "weight"], [[k, "%.3f" % v] for k, v in coefs.items()]), ""]

    path = P.report("RESULTS.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(md) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    main()
